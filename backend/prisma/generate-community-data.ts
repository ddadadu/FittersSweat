function getProductIdsForCategory(cat: string, index: number, count = 2): number[] {
  let base = 6;
  if (cat === 'shoes') base = 6;
  else if (cat === 'nutrition') base = 106;
  else if (cat === 'gear') base = 206;
  else if (cat === 'equipment') base = 306;

  const results: number[] = [];
  for (let i = 0; i < count; i++) {
    const id = base + ((index * 3 + i * 17) % 95);
    results.push(id);
  }
  return results;
}

